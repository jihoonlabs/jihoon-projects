def _fit_battle(rows):
    """Center-crop/pad hand-drawn rows to the fixed 16-pixel canvas."""
    fitted = []
    for row in rows:
        if len(row) > 16:
            start = (len(row) - 16) // 2
            row = row[start:start + 16]
        elif len(row) < 16:
            left = (16 - len(row)) // 2
            row = "." * left + row + "." * (16 - len(row) - left)
        fitted.append(row)
    return tuple(fitted)


