def draw_bitmap(display, x, y, rows, scale=1, mirror=False):
    """Draw a row-map with transparent pixels and carved black detail."""
    for row_index, row in enumerate(rows):
        for column, pixel in enumerate(row):
            if pixel == ".":
                continue
            draw_x = x + ((len(row) - 1 - column) if mirror else column) * scale
            draw_y = y + row_index * scale
            if pixel == "x":
                color = 0
            elif pixel == ":":
                if (column + row_index) % 2:
                    continue
                color = 1
            else:
                color = 1
            if scale == 1:
                display.setPixel(draw_x, draw_y, color)
            else:
                display.drawFilledRectangle(draw_x, draw_y, scale, scale, color)

